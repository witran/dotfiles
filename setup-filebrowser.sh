#!/usr/bin/env bash
# setup-filebrowser.sh — File Browser (https://filebrowser.org) on the VPS as a
# systemd service, reachable over HTTPS on the tailnet only. Run as the dev user
# (uses sudo), after setup-vps-root.sh:
#
#   bash setup-filebrowser.sh [root-dir]     # root-dir defaults to ~/code
#
# Everything it creates is in ~/.config/filebrowser, so you can inspect it:
#   filebrowser.service   systemd unit, linked into systemd with `systemctl link`
#   filebrowser.db        settings and users
#
# File Browser listens on 127.0.0.1:5000 only; `tailscale serve` puts it at
# https://<machine>.<tailnet>.ts.net with automatic certificates. Logs go to the
# journal (journald rotates them, so no logrotate/cron is needed):
#   journalctl -u filebrowser -f
#
# Idempotent — safe to re-run. Edit the unit, then re-run to apply it.
set -euo pipefail

PORT=5000
ROOT_DIR="${1:-$HOME/code}"
CONF_DIR="$HOME/.config/filebrowser"
DB="$CONF_DIR/filebrowser.db"
UNIT="$CONF_DIR/filebrowser.service"
BIN=/usr/local/bin/filebrowser
step() { printf '\n\033[1m== %s ==\033[0m\n' "$*"; }

if [ "$(uname -s)" != "Linux" ]; then
  echo "setup-filebrowser.sh is Linux-only." >&2; exit 1
fi
if [ "$(id -u)" -eq 0 ]; then
  echo "Run as the dev user, not root: the service runs as whoever runs this." >&2; exit 1
fi

# --- 1. Binary ----------------------------------------------------------------
step "filebrowser binary"
if [ -x "$BIN" ]; then
  echo "already installed: $("$BIN" version 2>/dev/null || echo "$BIN")"
else
  case "$(uname -m)" in
    x86_64)  ARCH=amd64 ;;
    aarch64) ARCH=arm64 ;;
    *) echo "Unsupported architecture: $(uname -m)" >&2; exit 1 ;;
  esac
  TMP="$(mktemp -d)"
  curl -fsSL "https://github.com/filebrowser/filebrowser/releases/latest/download/linux-$ARCH-filebrowser.tar.gz" \
    | tar -xz -C "$TMP" filebrowser
  sudo install -m 755 "$TMP/filebrowser" "$BIN"
  rm -rf "$TMP"
  echo "installed $BIN"
fi

# --- 2. Database and login ----------------------------------------------------
# Created only on the first run. Settings live in the unit's command line, so the
# database holds just the user. Change the password later with:
#   sudo systemctl stop filebrowser
#   filebrowser users update <user> --password <new> -d ~/.config/filebrowser/filebrowser.db
#   sudo systemctl start filebrowser
step "Database"
mkdir -p "$CONF_DIR" "$ROOT_DIR"
if [ -f "$DB" ]; then
  echo "already exists: $DB"
else
  while :; do
    read -rsp "Password for File Browser user '$USER' (12+ characters): " FB_PASS; echo
    [ "${#FB_PASS}" -ge 12 ] && break
    echo "Too short."
  done
  "$BIN" config init -d "$DB" >/dev/null
  "$BIN" users add "$USER" "$FB_PASS" --perm.admin -d "$DB" >/dev/null
  unset FB_PASS
  echo "created $DB with admin user '$USER'"
fi

# --- 3. systemd unit ----------------------------------------------------------
# The unit file stays here; `systemctl link` points systemd at it. Re-running this
# script overwrites it, so make lasting changes in this script.
step "systemd unit"
# systemd only follows linked units under /home if /home is on the root file
# system (it's read before other mounts at boot). True on a typical VPS.
if [ "$(findmnt -n -o TARGET --target "$CONF_DIR")" != "/" ]; then
  echo "!! $CONF_DIR is not on the root file system; systemd can't use a unit linked from there." >&2
  exit 1
fi
cat > "$UNIT" <<EOF
# Generated by setup-filebrowser.sh. Linked into systemd with:
#   sudo systemctl link $UNIT
[Unit]
Description=File Browser
Wants=network-online.target
After=network-online.target

[Service]
User=$USER
Group=$(id -gn)
ExecStart=$BIN --database $DB --address 127.0.0.1 --port $PORT --root $ROOT_DIR
Restart=on-failure
RestartSec=5
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
if [ "$(readlink /etc/systemd/system/filebrowser.service 2>/dev/null)" != "$UNIT" ]; then
  sudo systemctl link "$UNIT"
fi
sudo systemctl daemon-reload
sudo systemctl enable filebrowser >/dev/null 2>&1
sudo systemctl restart filebrowser
sleep 1
systemctl is-active --quiet filebrowser \
  || { echo "!! filebrowser did not start; see: journalctl -u filebrowser -n 50" >&2; exit 1; }
echo "running on 127.0.0.1:$PORT, serving $ROOT_DIR"

# --- 4. HTTPS on the tailnet --------------------------------------------------
# Needs HTTPS certificates enabled for the tailnet (admin console → DNS). --bg
# keeps the config across reboots.
step "tailscale serve"
sudo tailscale serve --bg "$PORT"

# --- 5. Summary ---------------------------------------------------------------
step "Done"
HOST="$(tailscale status --json | python3 -c "import sys,json; print(json.load(sys.stdin)['Self']['DNSName'].rstrip('.'))")"
echo "Open https://$HOST and log in as '$USER'."
echo "Unit: $UNIT   Logs: journalctl -u filebrowser -f"
